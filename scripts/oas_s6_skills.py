"""Sprint 6 WP100: skills routes. Run: python3 scripts/oas_s6_skills.py"""
import oas
oas.load()
oas.idschema('SkillId')
oas.idschema('SkillVersionId')
ROLE = 'enum:architect|worker|verifier|reviewer|researcher|writer'
oas.schema('SkillLintFlag', {'code': 's', 'line': 'i32', 'blocking': 'b'})
oas.schema('SkillLintWarning', {'code': 's', 'line': 'i32'})
oas.schema('SkillLint', {'flags': '[$SkillLintFlag]', 'warnings': '[$SkillLintWarning]'})
oas.schema('SkillVersionDto', {'id': '$SkillVersionId', 'skill_id': '$SkillId', 'number': 'i32', 'semver': 's', 'name': 's', 'description': 's', 'roles': '[%s]' % ROLE, 'when': 'enum:always|fix_round',
  'license': 's', 'source': 's', 'body': 's', 'content_sha256': 's', 'lint': '$SkillLint', 'state': 'enum:draft|approved|retired', 'acknowledged_flags': '[s]', 'approved_at': '?s', 'created_at': 's'})
oas.schema('SkillDto', {'id': '$SkillId', 'slug': 's', 'origin': 'enum:builtin|imported', 'title': 's', 'description': 's', 'roles': '[%s]' % ROLE, 'when': 'enum:always|fix_round', 'semver': '?s',
  'current_version_id': '$SkillVersionId', 'approved_version_id': '?$SkillVersionId', 'revision': 'i64', 'updated_at': 's'})
oas.schema('SkillList', {'items': '[$SkillDto]'})
oas.schema('SkillDetailDto', {'skill': '$SkillDto', 'versions': '[$SkillVersionDto]', 'update_available': 'b'})
oas.schema('ImportSkillRequest', {'filename': 's', 'content': 's'})
oas.schema('ApproveSkillVersionRequest', {'acknowledged_flags': '[s]'})
oas.schema('SkillBindingInput', {'role': ROLE, 'skill_id': '$SkillId', 'version_id': '$SkillVersionId', 'enabled': 'b', 'position': 'i32'})
oas.schema('SkillBindingSetDto', {'scope_key': 's', 'bindings': '[$SkillBindingInput]', 'revision': 'i64'})
oas.schema('PutSkillBindingsRequest', {'scope_key': 's', 'bindings': '[$SkillBindingInput]'})
oas.schema('SkillIncluded', {'skill_id': '$SkillId', 'version_id': '$SkillVersionId', 'slug': 's', 'semver': 's', 'sha256': 's', 'bytes': 'i32'})
oas.schema('SkillExcluded', {'slug': 's', 'reason': 's'})
oas.schema('SkillResolutionDto', {'included': '[$SkillIncluded]', 'excluded': '[$SkillExcluded]', 'bytes': 'i32', 'budget': 'i32'})
oas.schema('PinnedSkillDto', {'skill_id': 's', 'version_id': 's', 'slug': 's', 'semver': 's', 'sha256': 's'})
oas.schema('RunSkillRoleDto', {'round0': '[$PinnedSkillDto]', 'fix': '[$PinnedSkillDto]', 'excluded0': '[$SkillExcluded]', 'excluded_fix': '[$SkillExcluded]'})
oas.schema('RunSkillsDto', {'roles': 'obj', 'fingerprint': '?s'})
S = ('sklId', 'SkillId')
V = ('skvId', 'SkillVersionId')
oas.op('get', '/skills', 'list_skills', 'skills', resp='$SkillList')
oas.op('post', '/skills/import', 'import_skill', 'skills', idem=True, body='ImportSkillRequest', ok=201, resp='$SkillVersionDto')
oas.op('get', '/skills/{sklId}', 'get_skill', 'skills', params=[S], resp='$SkillDetailDto')
oas.op('get', '/skill-versions/{skvId}', 'get_skill_version', 'skills', params=[V], resp='$SkillVersionDto')
oas.op('post', '/skill-versions/{skvId}/approve', 'approve_skill_version', 'skills', params=[V], ifmatch=True, body='ApproveSkillVersionRequest', resp='$SkillDetailDto')
oas.op('post', '/skill-versions/{skvId}/retire', 'retire_skill_version', 'skills', params=[V], ifmatch=True, resp='$SkillDetailDto')
oas.op('get', '/skill-bindings', 'get_skill_bindings', 'skills', resp='$SkillBindingSetDto', query=[('scope_key', 's', '')])
oas.op('put', '/skill-bindings', 'put_skill_bindings', 'skills', ifmatch=True, body='PutSkillBindingsRequest', resp='$SkillBindingSetDto')
oas.op('post', '/skill-bindings/recommended', 'bind_recommended_skills', 'skills', idem=True, resp='$SkillBindingSetDto')
oas.op('get', '/skill-bindings/resolve', 'resolve_skill_bindings', 'skills', resp='$SkillResolutionDto', query=[('project_id', 's', ''), ('role', 's', ''), ('round', 'i32', '')])
oas.op('get', '/runs/{runId}/skills', 'get_run_skills', 'skills', params=[('runId', 'RunId')], resp='$RunSkillsDto')
oas.save()
