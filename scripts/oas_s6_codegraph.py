"""Sprint 6 WP101: code graph routes. Run: python3 scripts/oas_s6_codegraph.py"""
import oas
oas.load()
oas.idschema('CodeIndexId')
oas.schema('CodeIndexDto', {'id': '$CodeIndexId', 'project_id': 's', 'repo_key': 's', 'commit_sha': 's', 'state': 'enum:queued|indexing|ready|failed|license_revoked|removed', 'tool_version': '?s',
  'bytes': 'i64', 'files': 'i32', 'error_code': '?s', 'started_at': '?s', 'finished_at': '?s', 'revision': 'i64'})
oas.schema('CodeIndexList', {'items': '[$CodeIndexDto]'})
oas.schema('StartCodeIndexRequest', {'commit_sha': 's'}, [])
oas.schema('CodeImpactItem', {'path': 's', 'symbol': '?s', 'relation': 's', 'depth': 'i32'})
oas.schema('CodeImpactDto', {'commit_sha': 's', 'items': '[$CodeImpactItem]', 'truncated': 'b'})
oas.schema('CodeIndexRemovable', {'id': '$CodeIndexId', 'bytes': 'i64'})
oas.schema('CodeIndexRetentionPreview', {'removable': '[$CodeIndexRemovable]', 'total_bytes': 'i64'})
oas.schema('CodeGraphNewest', {'repo_key': 's', 'commit_sha': 's', 'finished_at': '?s'})
oas.schema('CodeGraphStatus', {'available': 'b', 'reason': '?s', 'ready_indexes': 'i32', 'newest': '?$CodeGraphNewest'})
oas.schema('GraphStatusDto', {'code_graph': '$CodeGraphStatus'})
C = ('cixId', 'CodeIndexId')
oas.op('get', '/graph/status', 'get_graph_status', 'graph', resp='$GraphStatusDto')
oas.op('get', '/code-indexes', 'list_code_indexes', 'graph', resp='$CodeIndexList', query=[('project_id', 's', ''), ('state', 's', '')])
oas.op('get', '/code-indexes/retention/preview', 'preview_code_index_retention', 'graph', resp='$CodeIndexRetentionPreview')
oas.op('get', '/code-indexes/{cixId}', 'get_code_index', 'graph', params=[C], resp='$CodeIndexDto')
oas.op('delete', '/code-indexes/{cixId}', 'delete_code_index', 'graph', params=[C], ifmatch=True, resp='$CodeIndexDto')
oas.op('get', '/code-indexes/{cixId}/impact', 'query_code_impact', 'graph', params=[C], resp='$CodeImpactDto', query=[('target', 's', ''), ('kind', 's', ''), ('depth', 'i32', ''), ('limit', 'i32', '')])
oas.op('post', '/projects/{prjId}/code-index', 'start_code_index', 'graph', params=[('prjId', 'ProjectId')], idem=True, body='StartCodeIndexRequest', ok=202, resp='$OperationDto')
oas.save()
